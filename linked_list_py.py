# Create Node class
class Node:
    def __init__(self, data):
        self.data = data
        self.next = None


# Create nodes
first = Node(10)
second = Node(20)
third = Node(30)

# Connect nodes
first.next = second
second.next = third

# Head pointer
head = first

# Display Linked List
temp = head

while temp is not None:
    print(temp.data, end=" -> ")
    temp = temp.next

print("None")

